-- user
ALTER TABLE `user`
  COMMENT = '微信用户基本信息',
  MODIFY COLUMN `id`         BIGINT       NOT NULL AUTO_INCREMENT COMMENT '用户ID',
  MODIFY COLUMN `openid`     VARCHAR(64)  NOT NULL COMMENT '微信OpenID，唯一标识',
  MODIFY COLUMN `nickname`   VARCHAR(64)  NOT NULL DEFAULT '' COMMENT '微信昵称',
  MODIFY COLUMN `avatar_url` VARCHAR(512) NOT NULL DEFAULT '' COMMENT '微信头像URL',
  MODIFY COLUMN `phone`      VARCHAR(20)           DEFAULT NULL COMMENT '手机号',
  MODIFY COLUMN `created_at` DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '注册时间';

