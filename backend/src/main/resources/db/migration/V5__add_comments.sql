-- activity
ALTER TABLE `activity`
  COMMENT = '球队活动（比赛或训练）',
  MODIFY COLUMN `id`          BIGINT       NOT NULL AUTO_INCREMENT COMMENT '活动ID',
  MODIFY COLUMN `team_id`     BIGINT       NOT NULL COMMENT '所属球队ID',
  MODIFY COLUMN `type`        VARCHAR(16)  NOT NULL COMMENT '活动类型：MATCH比赛/TRAINING训练',
  MODIFY COLUMN `title`       VARCHAR(128) NOT NULL COMMENT '活动标题',
  MODIFY COLUMN `opponent`    VARCHAR(64)           DEFAULT NULL COMMENT '对手球队名称（仅比赛）',
  MODIFY COLUMN `location`    VARCHAR(128) NOT NULL DEFAULT '' COMMENT '活动地点',
  MODIFY COLUMN `start_time`  DATETIME     NOT NULL COMMENT '开始时间',
  MODIFY COLUMN `deadline`    DATETIME              DEFAULT NULL COMMENT '报名截止时间，NULL表示不限',
  MODIFY COLUMN `max_players` INT                   DEFAULT NULL COMMENT '最大报名人数，NULL表示不限',
  MODIFY COLUMN `status`      VARCHAR(16)  NOT NULL DEFAULT 'OPEN' COMMENT '状态：OPEN报名中/CLOSED已截止/FINISHED已结束',
  MODIFY COLUMN `created_by`  BIGINT       NOT NULL COMMENT '创建人用户ID',
  MODIFY COLUMN `created_at`  DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间';

